const TABLES: Record<Lang, Record<MessageKey, string>> = {
  ru,
  kz: kk,
  en,
};

export function t(
  lang: Lang,
  key: MessageKey,
  vars?: Record<string, string | number>,
): string {
  const table = TABLES[lang] ?? ru;
  let out = table[key] ?? ru[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      out = out.replaceAll(`{${k}}`, String(v));
    }
  }
  return out;
}

export function dayNameKeys(index: number): {
  full: MessageKey;
  short: MessageKey;
} {
  const map = [
    { full: "day_mon", short: "day_mon_short" },
    { full: "day_tue", short: "day_tue_short" },
    { full: "day_wed", short: "day_wed_short" },
    { full: "day_thu", short: "day_thu_short" },
    { full: "day_fri", short: "day_fri_short" },
    { full: "day_sat", short: "day_sat_short" },
    { full: "day_sun", short: "day_sun_short" },
  ] as const;
  return map[((index % 7) + 7) % 7]!;
}

export function historyWord(lang: Lang, n: number): string {
  if (lang === "en") {
    return t(lang, n === 1 ? "history_word_one" : "history_word_many");
  }
  if (lang === "kz") {
    return t(lang, "history_word_many");
  }
  const mod10 = n % 10;
  const mod100 = n % 100;
  if (mod10 === 1 && mod100 !== 11) return t(lang, "history_word_one");
  if (mod10 >= 2 && mod10 <= 4 && (mod100 < 12 || mod100 > 14)) {
    return t(lang, "history_word_few");
  }
  return t(lang, "history_word_many");
}
